"""Generate static/js/who-growth.js from the WHO Child Growth Standards tables (birth to 5 years).

    python scripts/make_growth_data.py

Downloads WHO's monthly percentile tables (weight, length/height and head circumference for age; boys and girls),
checks that the L, M and S values reproduce the published percentiles, and writes them per completed month.
Length is measured lying down up to 24 months and standing from 24 months (about 0.7 cm less), so the length table
has the standing values from 24 months on and keeps the lying value at 24 months separately (`lying24`).
The data is WHO's, under WHO's terms (non-commercial use with attribution), not the MIT license of this repository.
"""
import io
import json
import math
import urllib.request
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "js" / "who-growth.js"
BASE = "https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/"
FILES = {
    "weight": ["weight-for-age/tab_wfa_{sex}_p_0_5.xlsx"],
    "length": ["length-height-for-age/tab_lhfa_{sex}_p_0_2.xlsx", "length-height-for-age/tab_lhfa_{sex}_p_2_5.xlsx"],
    "head": ["head-circumference-for-age/tab_hcfa_{sex}_p_0_5.xlsx"],
}
MAX_MONTHS = 60
# Published percentile columns (rounded to 0.1) and their z-scores
CHECKS = {"P3": -1.880794, "P15": -1.036433, "P50": 0.0, "P85": 1.036433, "P97": 1.880794}
SHEET = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"

HEADER = """// WHO Child Growth Standards (2006): L, M and S per completed month from birth to 60 months,
// for weight-for-age (kg), length/height-for-age (cm) and head circumference-for-age (cm), boys and girls.
// Length: lying down up to 24 months ("lying24" is the lying value at 24 months), standing height from 24 months.
//
// Source: World Health Organization, WHO Child Growth Standards, https://www.who.int/tools/child-growth-standards
// This data is WHO's and is used under WHO's terms (non-commercial use with acknowledgement of WHO as the source).
// It is NOT covered by the MIT license of this repository. Generated by scripts/make_growth_data.py.
"""


def value_at(lms, z):
    L, M, S = lms
    return M * math.exp(S * z) if L == 0 else M * (1 + L * S * z) ** (1 / L)


def xlsx_rows(data):
    """The first sheet of an .xlsx file as dicts by header (standard library only)."""
    book = zipfile.ZipFile(io.BytesIO(data))
    shared = []
    if "xl/sharedStrings.xml" in book.namelist():
        for item in ET.fromstring(book.read("xl/sharedStrings.xml")).iter(f"{SHEET}si"):
            shared.append("".join(t.text or "" for t in item.iter(f"{SHEET}t")))
    rows = []
    for row in ET.fromstring(book.read("xl/worksheets/sheet1.xml")).iter(f"{SHEET}row"):
        cells = []
        for cell in row.iter(f"{SHEET}c"):
            value = cell.find(f"{SHEET}v")
            text = value.text if value is not None else ""
            cells.append(shared[int(text)] if cell.get("t") == "s" else text)
        rows.append(cells)
    header = [h.strip() for h in rows[0]]
    return [dict(zip(header, r, strict=False)) for r in rows[1:] if r]


def load(path):
    # WHO's server refuses Python's default User-Agent
    request = urllib.request.Request(BASE + path, headers={"User-Agent": "baby-calculator/make_growth_data"})
    with urllib.request.urlopen(request, timeout=30) as response:
        rows = xlsx_rows(response.read())
    table = {}
    for row in rows:
        month = int(float(row["Month"]))
        lms = [float(row["L"]), float(row["M"]), float(row["S"])]
        for column, z in CHECKS.items():
            published = float(row[column])
            assert abs(value_at(lms, z) - published) <= 0.051, (path, month, column, value_at(lms, z), published)
        table[month] = [round(v, 5) for v in lms]
    return table


def main():
    data = {}
    for sex in ("boys", "girls"):
        data[sex] = {}
        for measure, paths in FILES.items():
            parts = [load(p.format(sex=sex)) for p in paths]
            rows = {**parts[0], **parts[-1]}  # length: the standing table wins from 24 months
            assert sorted(rows) == list(range(MAX_MONTHS + 1)), (sex, measure, sorted(rows))
            entry = {"rows": [rows[m] for m in range(MAX_MONTHS + 1)]}
            if len(parts) > 1:
                entry["lying24"] = parts[0][24]
                assert 0.5 < entry["lying24"][1] - rows[24][1] < 0.9  # lying is ~0.7 cm longer than standing
            data[sex][measure] = entry
    body = json.dumps(data, separators=(",", ":"))
    OUT.write_text(HEADER + "(function (BC) {\n    'use strict';\n\n    BC.WHO_GROWTH = " + body +
                   ";\n})(globalThis.BC = globalThis.BC || {});\n")
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size // 1024} KB, all published percentiles reproduced")


if __name__ == "__main__":
    main()
