"""Generate static/js/who-growth.js from the CDC copies of the WHO Child Growth Standards (birth to 24 months).

    python scripts/make_growth_data.py

Downloads the six CSV files (weight, length and head circumference for age; boys and girls), checks that the LMS
parameters reproduce the published percentiles, and writes the L, M and S values per completed month.
The data is WHO's, under WHO's terms (non-commercial use with attribution), not the MIT license of this repository.
"""
import csv
import io
import json
import math
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "static" / "js" / "who-growth.js"
BASE = "https://ftp.cdc.gov/pub/Health_Statistics/NCHS/growthcharts/"
FILES = {
    ("boys", "weight"): "WHO-Boys-Weight-for-age-Percentiles.csv",
    ("girls", "weight"): "WHO-Girls-Weight-for-age%20Percentiles.csv",
    ("boys", "length"): "WHO-Boys-Length-for-age-Percentiles.csv",
    ("girls", "length"): "WHO-Girls-Length-for-age-Percentiles.csv",
    ("boys", "head"): "WHO-Boys-Head-Circumference-for-age-Percentiles.csv",
    ("girls", "head"): "WHO-Girls-Head-Circumference-for-age-Percentiles.csv",
}
# Published percentile columns and their z-scores
CHECKS = {"5th": -1.6448536, "25th": -0.6744898, "50th": 0.0, "75th": 0.6744898, "95th": 1.6448536}

HEADER = """// WHO Child Growth Standards (2006): L, M and S per completed month from birth to 24 months,
// for weight-for-age (kg), length-for-age (cm) and head circumference-for-age (cm), boys and girls.
//
// Source: World Health Organization, WHO Child Growth Standards, https://www.who.int/tools/child-growth-standards
// via the CDC data files, https://www.cdc.gov/growthcharts/who-data-files.htm
// This data is WHO's and is used under WHO's terms (non-commercial use with acknowledgement of WHO as the source).
// It is NOT covered by the MIT license of this repository. Generated by scripts/make_growth_data.py.
"""


def value_at(lms, z):
    L, M, S = lms
    return M * math.exp(S * z) if L == 0 else M * (1 + L * S * z) ** (1 / L)


def load(name):
    with urllib.request.urlopen(BASE + name, timeout=30) as response:
        text = response.read().decode("utf-8-sig")
    rows = list(csv.DictReader(io.StringIO(text)))
    table = []
    for month, row in enumerate(rows):
        assert int(float(row["Month"])) == month, (name, row["Month"])
        lms = [float(row["L"]), float(row["M"]), float(row["S"])]
        for column, z in CHECKS.items():
            published = float(row[column])
            assert abs(value_at(lms, z) - published) < 0.01, (name, month, column, value_at(lms, z), published)
        table.append(lms)
    assert len(table) == 25, (name, len(table))
    return table


def main():
    data = {"boys": {}, "girls": {}}
    for (sex, measure), name in FILES.items():
        data[sex][measure] = load(name)
    body = json.dumps(data, separators=(",", ":"))
    OUT.write_text(HEADER + "(function (BC) {\n    'use strict';\n\n    BC.WHO_GROWTH = " + body +
                   ";\n})(globalThis.BC = globalThis.BC || {});\n")
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size // 1024} KB, all published percentiles reproduced")


if __name__ == "__main__":
    main()
